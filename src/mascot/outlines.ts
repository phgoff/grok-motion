export type SeatKind = "front" | "sphere";

export function outlineFor(shape: BodyShape): readonly XY[] | undefined {
  if (shape === "sphere") return undefined;
  return BODY_OUTLINES[shape];
}

const OUTLINE_TO_STOCK_SHAPE = new Map<readonly XY[], BodyShape>(
  (Object.entries(BODY_OUTLINES) as [BodyShape, readonly XY[]][]).map(([shape, outline]) => [
    outline,
    shape,
  ]),
);

export function stockShapeIdFor(outline: readonly XY[] | undefined): BodyShape | undefined {
  return outline ? OUTLINE_TO_STOCK_SHAPE.get(outline) : undefined;
}

const FRONT_SEATED: ReadonlySet<BodyShape> = new Set([
  "squircle",
  "hex",
  "sparkle",
  "clover",
  "flower",
  "house",
  "star",
]);

const OUTLINE_TO_SEAT = (() => {
  const map = new WeakMap<readonly XY[], SeatKind>();
  for (const [shape, outline] of Object.entries(BODY_OUTLINES)) {
    map.set(outline, FRONT_SEATED.has(shape as BodyShape) ? "front" : "sphere");
  }
  return map;
})();

export function seatForOutline(outline: readonly XY[] | undefined): SeatKind {
  if (!outline) return "sphere";
  return OUTLINE_TO_SEAT.get(outline) ?? "sphere";
}
